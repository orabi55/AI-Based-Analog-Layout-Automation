class TestMovePairExpansion:
    def test_validator_expands_move_pair(self):
        state = {
            "pending_cmds": [{
                "action": "move_pair",
                "devices": ["M1", "M2"],
                "dx": 1,
                "dy": 0,
            }],
            "placement_nodes": _make_nodes(),
        }
        result = node_command_validator(state)
        # Should be expanded into 2 individual move commands
        assert len(result["pending_cmds"]) == 2
        actions = {c["action"] for c in result["pending_cmds"]}
        assert actions == {"move"}
        device_ids = {c["device_id"] for c in result["pending_cmds"]}
        assert device_ids == {"M1", "M2"}


