class TestRowCrossingBlocking:
    def test_validator_blocks_row_crossing_absolute_y(self):
        state = {
            "pending_cmds": [{"action": "move", "device_id": "M1", "y": -10}],
            "placement_nodes": [{"id": "M1", "type": "nmos", "y": 100, "geometry": {"y": 100}}],
        }
        result = node_command_validator(state)
        assert result["pending_cmds"] == []
        assert result["validation_errors"]

    def test_validator_allows_row_crossing_with_force_y(self):
        state = {
            "pending_cmds": [{"action": "move", "device_id": "M1", "y": -10, "force_y": True}],
            "placement_nodes": [{"id": "M1", "type": "nmos", "y": 100, "geometry": {"y": 100}}],
        }
        result = node_command_validator(state)
        assert result["pending_cmds"]
        assert result["validation_warnings"]

    def test_validator_allows_same_row_move(self):
        state = {
            "pending_cmds": [{"action": "move", "device_id": "M1", "y": 110}],
            "placement_nodes": [{"id": "M1", "type": "nmos", "y": 100, "geometry": {"y": 100}}],
        }
        result = node_command_validator(state)
        assert result["pending_cmds"]

    def test_validator_allows_relative_dy_move(self):
        """Relative dy moves should not trigger row legality check."""
        state = {
            "pending_cmds": [{"action": "move", "device_id": "M1", "dy": -1}],
            "placement_nodes": [{"id": "M1", "type": "nmos", "y": 100, "geometry": {"y": 100}}],
        }
        result = node_command_validator(state)
        assert result["pending_cmds"]
        assert not result["validation_errors"]


