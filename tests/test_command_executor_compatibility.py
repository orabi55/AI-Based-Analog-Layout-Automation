class TestUnsupportedActionsRejected:
    def test_validator_rejects_align(self):
        state = {
            "pending_cmds": [{"action": "align", "device_a": "M1", "device_b": "M2"}],
            "placement_nodes": _make_nodes(),
        }
        result = node_command_validator(state)
        assert result["pending_cmds"] == []
        assert result["validation_errors"]

    def test_validator_rejects_merge(self):
        state = {
            "pending_cmds": [{"action": "merge", "device_a": "M1", "device_b": "M2"}],
            "placement_nodes": _make_nodes(),
        }
        result = node_command_validator(state)
        assert result["pending_cmds"] == []

    def test_validator_rejects_rotate(self):
        state = {
            "pending_cmds": [{"action": "rotate", "device_id": "M1"}],
            "placement_nodes": _make_nodes(),
        }
        result = node_command_validator(state)
        assert result["pending_cmds"] == []

    def test_all_validator_allowed_actions_are_executor_supported(self):
        from ai_agent.nodes.command_validator import ALLOWED_ACTIONS
        expected_superset = SUPPORTED_COMMAND_ACTIONS | {"move_pair", "add dummy"}
        assert set(ALLOWED_ACTIONS).issubset(expected_superset)

    @pytest.mark.parametrize("msg", [
        "align M1 with M2",
        "merge M1 and M2",
        "rotate M1",
    ])
    def test_unsupported_actions_route_to_clarify(self, msg):
        result = run_session_chat_agent({
            "user_message": msg,
            "placement_nodes": [{"id": "M1"}, {"id": "M2"}],
        })
        assert result["session_route"] == "clarify"
        assert "not currently supported" in result["assistant_text"].lower()


