node_session_finalizer = _sf.node_session_finalizer


class TestFinalizerSpecialistResultPriority:
    """Specialist results must override any stale router placeholder text."""

    def test_strategy_result_used_over_placeholder(self):
        state = {
            "session_route": "need_strategy",
            "assistant_text": "I'll delegate this to the strategy_selector...",
            "strategy_result": "MM3 and MM0 appear to be interdigitated.",
        }
        result = node_session_finalizer(state)
        assert "interdigitated" in result["assistant_text"]
        assert "delegate" not in result["assistant_text"]

    def test_strategy_result_used_when_assistant_text_is_none(self):
        state = {
            "session_route": "need_strategy",
            "assistant_text": None,
            "strategy_result": "Common-centroid pattern detected.",
        }
        result = node_session_finalizer(state)
        assert "Common-centroid" in result["assistant_text"]

    def test_topology_result_used_over_placeholder(self):
        state = {
            "session_route": "need_topology",
            "assistant_text": "Delegating to topology_analyst...",
            "Analysis_result": "Found 4 NMOS devices and 4 PMOS devices.",
        }
        result = node_session_finalizer(state)
        assert "4 NMOS" in result["assistant_text"]
        assert "Delegating" not in result["assistant_text"]

    def test_drc_result_used_over_placeholder(self):
        state = {
            "session_route": "need_drc",
            "assistant_text": "Running DRC check...",
            "drc_pass": True,
            "drc_flags": [],
        }
        result = node_session_finalizer(state)
        assert "pass" in result["assistant_text"].lower()

    def test_routing_result_used_over_placeholder(self):
        state = {
            "session_route": "need_routing",
            "assistant_text": "Delegating to routing previewer...",
            "routing_result": {"log_text": "9 nets analyzed, HPWL = 12.3µm"},
        }
        result = node_session_finalizer(state)
        assert "9 nets" in result["assistant_text"]
        assert "Delegating" not in result["assistant_text"]

    def test_generic_fallback_when_specialist_has_no_result(self):
        state = {
            "session_route": "need_strategy",
            "assistant_text": None,
            "strategy_result": "",
        }
        result = node_session_finalizer(state)
        # Should get the generic fallback, not empty
        assert result["assistant_text"]
        assert "completed" in result["assistant_text"].lower()

    def test_router_does_not_set_placeholder_for_specialist_routes(self):
        """run_session_chat_agent should set assistant_text to None for specialists."""
        result = run_session_chat_agent({
            "user_message": "what matching strategy did you use?",
            "placement_nodes": [{"id": "M1"}, {"id": "M2"}],
        })
        route = result["session_route"]
        if route in ("need_strategy", "need_topology", "need_routing", "need_drc", "fix_drc"):
            # For specialist routes, assistant_text should be None
            # (not a stale placeholder)
            assert result["assistant_text"] is None, (
                f"Router should not set placeholder text for specialist route "
                f"'{route}', got: {result['assistant_text']!r}"
            )

    def test_non_specialist_route_keeps_assistant_text(self):
        """For answer_only, the finalizer should keep existing assistant_text."""
        state = {
            "session_route": "answer_only",
            "assistant_text": "The layout has 8 devices total.",
        }
        result = node_session_finalizer(state)
        assert "8 devices" in result["assistant_text"]
