class TestAddDummyContext:
    def test_parse_vague_add_dummy_returns_empty(self):
        assert parse_direct_edit_command("add dummy") == []

    def test_parse_add_dummy_left_of_device(self):
        cmds = parse_direct_edit_command("add dummy left of M1")
        assert cmds
        assert cmds[0]["action"] == "add_dummy"
        assert cmds[0].get("target") == "M1"
        assert cmds[0].get("side") == "left"

    def test_parse_add_dummy_right_of_device(self):
        cmds = parse_direct_edit_command("add dummy right of M1")
        assert cmds
        assert cmds[0]["side"] == "right"

    def test_parse_add_dummy_near_device(self):
        cmds = parse_direct_edit_command("add dummy near M1")
        assert cmds
        assert cmds[0]["target"] == "M1"

    def test_validator_rejects_add_dummy_without_context(self):
        state = {
            "pending_cmds": [{"action": "add_dummy"}],
            "placement_nodes": [{"id": "M1"}],
        }
        result = node_command_validator(state)
        assert result["pending_cmds"] == []
        assert result["session_route"] == "clarify"

    def test_add_dummy_left_of_m1_is_normalized_to_xy(self):
        nodes = [{"id": "M1", "type": "nmos", "geometry": {"x": 1.0, "y": 0.5, "width": 0.294}}]
        state = {
            "pending_cmds": [{"action": "add_dummy", "target": "M1", "side": "left"}],
            "placement_nodes": nodes,
        }
        result = node_command_validator(state)
        assert result["pending_cmds"]
        resolved = result["pending_cmds"][0]
        assert resolved.get("x") is not None
        assert resolved.get("y") is not None
        # Left of M1: x should be less than M1's x
        assert resolved["x"] < 1.0
        assert resolved["y"] == 0.5


