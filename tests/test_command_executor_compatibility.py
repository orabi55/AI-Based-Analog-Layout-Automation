def _make_nodes():
    return [
        {"id": "M1", "type": "nmos", "geometry": {"x": 10.0, "y": 0.0, "width": 0.294, "height": 0.668, "orientation": "R0"}},
        {"id": "M2", "type": "nmos", "geometry": {"x": 20.0, "y": 0.0, "width": 0.294, "height": 0.668, "orientation": "R0"}},
    ]


