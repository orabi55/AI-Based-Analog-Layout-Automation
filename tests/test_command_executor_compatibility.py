class TestExplanationFingerExtraction:
    def test_explanation_extracts_logical_device_from_fingers(self):
        nodes = [
            {"id": "M1_f0", "parent_id": "M1"},
            {"id": "M1_f1", "parent_id": "M1"},
        ]
        trace = {"strategy": {"matching_groups": [["M1", "M2"]]}}
        text = answer_from_initial_trace(
            "why did you place M1 here?", trace, nodes,
        )
        assert "M1" in text
        assert "M2" in text

    def test_extract_devices_for_explanation_with_fingers(self):
        nodes = [
            {"id": "M1_f0", "parent_id": "M1"},
            {"id": "M1_f1", "parent_id": "M1"},
        ]
        trace = {"strategy": {"matching_groups": [["M1", "M2"]]}}
        devs = _extract_devices_for_explanation(
            "why did you place M1 here?", nodes, trace,
        )
        assert "M1" in devs

    def test_logical_base_device_id(self):
        assert logical_base_device_id("M1_f0") == "M1"
        assert logical_base_device_id("M1_finger0") == "M1"
        assert logical_base_device_id("M1[0]") == "M1"
        assert logical_base_device_id("M1__finger0") == "M1"
        assert logical_base_device_id("M1") == "M1"


